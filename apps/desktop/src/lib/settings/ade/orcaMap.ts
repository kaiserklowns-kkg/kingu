// Orca settings → Kingu, for the user-facing settings Orca has (shared/global-settings-types.ts,
// persisted UI preferences, per-repo settings and orca.yaml). Internal state Orca keeps in the
// same objects (migration guards, caches, account records) is left out.
//
// status: `added` — a kingu.* key here does what Orca's does; `mapped` — an existing Kingu key
// (often a VS Code one) already covers it, so no second key; `needs-feature` — Kingu lacks the
// feature (`note` names it); `not-applicable` — Orca-architecture or Windows-only.
// registry tests check that every `added` / `mapped` kingu.* key exists and every ADE setting
// is listed here.

