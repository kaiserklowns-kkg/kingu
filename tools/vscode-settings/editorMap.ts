// Writes apps/desktop/src/lib/settings/editorOptionMap.ts: for every editor.* and diffEditor.*
// setting Kingu registers, where its value goes in Monaco (VS Code passes the `editor` section of
// the configuration straight to the editor as IEditorOptions, so `editor.minimap.enabled` is the
// option `minimap.enabled`). Settings Monaco reads only from its configuration service, and the
// ones Kingu applies itself (model indentation, save participants), are listed apart. The paths
// are type-checked against Monaco's IEditorOptions / IDiffEditorOptions, and editorOptions.test.ts
// checks them against Monaco's own option registry.
//
//   bun tools/vscode-settings/editorMap.ts

import { join } from 'node:path';
import { SETTINGS } from '../../apps/desktop/src/lib/settings/registry.ts';

const OUT = join(import.meta.dir, '../../apps/desktop/src/lib/settings/editorOptionMap.ts');

/** Applied by Kingu itself rather than as editor options (see apply.svelte.ts, textFileSave.ts). */
const KINGU = ['editor.tabSize', 'editor.indentSize', 'editor.insertSpaces', 'editor.detectIndentation', 'editor.trimAutoWhitespace', 'editor.formatOnSave', 'editor.codeActionsOnSave', 'editor.codeActions.triggerOnFocusChange'];
/** IGlobalEditorOptions fields (updateOptions forwards them to Monaco's configuration service). */
const GLOBAL = ['largeFileOptimizations', 'wordBasedSuggestions', 'stablePeek', 'maxTokenizationLineLength'];
/** diffEditor.* keys whose IDiffEditorOptions field has another name. */
const DIFF_RENAMED: Record<string, string> = { 'diffEditor.wordWrap': 'diffWordWrap' };
/** Options Monaco validates and applies (editorOptions.test.ts) that its public .d.ts leaves out. */
const UNTYPED = ['editor.find.history', 'editor.find.replaceHistory', 'diffEditor.hideOriginalLineNumbers'];

// Monaco is a dependency of the desktop app, not of the repository root.
const { EditorOptions } = await import(join(import.meta.dir, '../../apps/desktop/node_modules/monaco-editor/esm/vs/editor/common/config/editorOptions.js'));
const names = new Set(Object.values(EditorOptions as Record<string, { name: string }>).map((o) => o.name));
const options: [string, string][] = [];
const config: string[] = [];
const diff: [string, string][] = [];
for (const { id } of SETTINGS) {
	if (id.startsWith('editor.')) {
		if (KINGU.includes(id)) continue;
		const path = id.slice('editor.'.length);
		const head = path.split('.')[0];
		if (names.has(head) || GLOBAL.includes(path)) options.push([id, path]);
		else config.push(id);
	} else if (id.startsWith('diffEditor.')) diff.push([id, DIFF_RENAMED[id] ?? id.slice('diffEditor.'.length)]);
}
options.sort(([a], [b]) => a.localeCompare(b));
config.sort();
diff.sort(([a], [b]) => a.localeCompare(b));

const text = `// Generated by tools/vscode-settings/editorMap.ts from the registered settings; run it again after
// adding an editor.* or diffEditor.* setting. Where each setting goes in Monaco: VS Code hands the
// \`editor\` configuration section to the editor as IEditorOptions, so \`editor.minimap.enabled\` is
// the option \`minimap.enabled\`. The paths are checked against Monaco's option types here and
// against its option registry in editorOptions.test.ts.
import type * as Monaco from 'monaco-editor';

type Options = Monaco.editor.IEditorOptions & Monaco.editor.IGlobalEditorOptions;
type DiffOptions = Monaco.editor.IDiffEditorOptions;
type Nested<T> = Exclude<NonNullable<T>, boolean | string | number | readonly unknown[] | ((...args: never[]) => unknown)>;
/** \`name\` or \`name.sub\` of an option object. */
export type OptionPath<O> = { [K in keyof O & string]-?: K | ([Nested<O[K]>] extends [never] ? never : \`\${K}.\${keyof Nested<O[K]> & string}\`) }[keyof O & string];

const TYPED_EDITOR_OPTION_PATHS = {
${options.filter(([id]) => !UNTYPED.includes(id)).map(([id, p]) => `\t'${id}': '${p}'`).join(',\n')}
} as const satisfies Record<string, OptionPath<Options>>;

/** editor.* settings that are Monaco editor options, with the option path. */
export const EDITOR_OPTION_PATHS: Readonly<Record<string, string>> = {
	...TYPED_EDITOR_OPTION_PATHS,
	// Monaco validates and applies these (editorOptions.test.ts) but its public types leave them out.
${options.filter(([id]) => UNTYPED.includes(id)).map(([id, p]) => `\t'${id}': '${p}'`).join(',\n')}
};

/** editor.* settings Monaco reads only from its configuration service (no IEditorOptions field). */
export const EDITOR_CONFIG_SETTINGS = [${config.map((id) => `'${id}'`).join(', ')}] as const;

/** editor.* settings Kingu applies itself: model indentation (apply.svelte.ts) and save participants (textFileSave.ts). */
export const EDITOR_KINGU_SETTINGS = [${KINGU.map((id) => `'${id}'`).join(', ')}] as const;

const TYPED_DIFF_EDITOR_OPTION_PATHS = {
${diff.filter(([id]) => !UNTYPED.includes(id)).map(([id, p]) => `\t'${id}': '${p}'`).join(',\n')}
} as const satisfies Record<string, OptionPath<DiffOptions>>;

/** diffEditor.* settings, with the IDiffEditorOptions path. */
export const DIFF_EDITOR_OPTION_PATHS: Readonly<Record<string, string>> = {
	...TYPED_DIFF_EDITOR_OPTION_PATHS,
	// Monaco validates and applies these but its public types leave them out.
${diff.filter(([id]) => UNTYPED.includes(id)).map(([id, p]) => `\t'${id}': '${p}'`).join(',\n')}
};
`;
await Bun.write(OUT, text);
console.log(`${options.length} options, ${config.length} config-only, ${diff.length} diff -> ${OUT}`);
process.exit(0);
